"""raw/ (64x64 เต็มตัว หัวโล้น + หัวมีผม) -> frames/ + anchors ใหม่

เกมวาด body ไม่มีหัว แล้ววาง head 64x48 ทับที่ (dx+ax, dy+ay)
anchor จึงต้องอ้างอิง "กะโหลก" ซึ่งเหมือนกันทุกทรงผม ไม่ใช่ bbox ของผม
(ผมยาวล้นออกนอกกะโหลก ถ้าอ้างอิงขอบผมจะเลื่อนไม่ตรงกันแต่ละทรง)
"""
import os, json
from PIL import Image
from decompose import neck_y

FRAME={"novice":(64,112),"swordman":(96,112)}
FEET=108; HW,HH=64,48
SLOTS=["down","side","up"]
ROW={"down":0,"side":1,"up":3}          # row2 (ขวา) สร้างจากการพลิก side
COLMAP=[("base",0),("base",0),("walk",0),("walk",1),("walk",2),("walk",3),
        ("attack",0),("attack",1),("attack",2),("base",0),
        ("death",0),("death",1),("death",2)]
SKULL_Y=6                                # กะโหลกวางที่ y นี้ในผืน 64x48

def rawp(cls,slot,anim,idx):
    """raw2/ ถือเฟรมที่ generate ใหม่ ใช้ก่อน raw/ เสมอ; ถ้าไม่มีเลยถอยไปท่ายืน"""
    if anim=="base": return f"raw/{cls}_{slot}_base.png"
    for d in ("raw2","raw"):
        p=f"{d}/{cls}_{slot}_{anim}_{idx}.png"
        if os.path.exists(p): return p
    return f"raw/{cls}_{slot}_base.png"

def cut(img,ny):
    """แยกเป็น (เหนือคอ, ใต้คอ)"""
    top=Image.new('RGBA',img.size,(0,0,0,0)); bot=Image.new('RGBA',img.size,(0,0,0,0))
    ip,tp,bp=img.load(),top.load(),bot.load()
    for y in range(img.height):
        dst=tp if y<ny else bp
        for x in range(img.width): dst[x,y]=ip[x,y]
    return top,bot

def bbox(im): return im.getchannel('A').getbbox()

os.makedirs("frames",exist_ok=True)
anchors={}

# ---- หัว: ใช้กะโหลกของ base แต่ละทิศเป็นจุดอ้างอิงร่วม ----
skull={}
for slot in SLOTS:
    base=Image.open(f"raw/novice_{slot}_base.png").convert('RGBA')
    ny=neck_y(base); head,_=cut(base,ny)
    skull[slot]=(bbox(head),ny)

n_styles=0
for i in range(32):
    if not os.path.exists(f"raw/hair{i:02d}_down.png"): break
    n_styles=i+1
for i in range(n_styles):
    for slot in SLOTS:
        sk,ny=skull[slot]
        full=Image.open(f"raw/hair{i:02d}_{slot}.png").convert('RGBA')
        head,_=cut(full,ny)
        canvas=Image.new('RGBA',(HW,HH),(0,0,0,0))
        # วางให้กะโหลก (sk) ไปอยู่ที่ (SX, SKULL_Y)
        SX=HW//2-(sk[2]-sk[0])//2
        canvas.paste(head,(SX-sk[0], SKULL_Y-sk[1]),head)
        canvas.save(f"frames/hair_{i:02d}_{slot}.png")

# ---- ตัว + anchors ----
for cls,(fw,fh) in FRAME.items():
    grid=[[None]*13 for _ in range(4)]
    for slot in SLOTS:
        sk,_=skull[slot]
        SX=HW//2-(sk[2]-sk[0])//2
        for col,(anim,idx) in enumerate(COLMAP):
            full=Image.open(rawp(cls,slot,anim,idx)).convert('RGBA')
            ny=neck_y(full)
            head,body=cut(full,ny)
            hb,bb=bbox(head),bbox(body)
            if bb is None: continue
            crop=body.crop(bb)
            X=(fw-crop.width)//2; Y=FEET-crop.height
            out=Image.new('RGBA',(fw,fh),(0,0,0,0)); out.paste(crop,(X,Y),crop)
            out.save(f"frames/body_{cls}_{slot}_{col:02d}.png")
            if hb:
                hx=hb[0]-bb[0]+X; hy=hb[1]-bb[1]+Y      # กะโหลกเฟรมนี้ ในพิกัดกรอบ
                grid[ROW[slot]][col]=[hx-SX, hy-SKULL_Y]
        if slot=="side":                                  # row2 = กระจกของ row1
            for col in range(13):
                a=grid[1][col]
                if a: grid[2][col]=[fw-HW-a[0], a[1]]
    for r in range(4):
        for c in range(13):
            if grid[r][c] is None: grid[r][c]=grid[0][0] or [0,20]
    anchors[cls]=grid

js=("// Generated by tools/build-sprite-atlas.py from the frames it composed.\n"
    "// Head placement is measured against the bald skull of each body frame, which is\n"
    "// consistent across hairstyles; hair silhouettes are not.\n"
    '(function(root){root.BorderSpriteAnchors=%s;})(typeof window!=="undefined"?window:globalThis);\n'
    % json.dumps(anchors,separators=(',',':')))
open("frames/sprite-anchors.js","w").write(js)
print(f"frames: {len([f for f in os.listdir('frames') if f.endswith('.png')])} png, ทรงผม {n_styles} ทรง")
