'use strict';
const assert = require('node:assert/strict');
const Codex = require('../js/divine-pride-codex.js');
const Core = require('../js/core.js');
const empty = {schema:1,region:'thROC',fetchedAt:null,monsters:{},items:{},skills:{}};
const sample = {...empty,fetchedAt:'2026-09-18T06:00:00Z',monsters:{'1002':{id:1002,name:'Poring',health:60,level:1,def:0,region:'thROC',element:'Water'}},items:{'501':{id:501,name:'Red Potion',buyPrice:50,weight:70}},skills:{'7':{id:7,name:'Magnum Break',maxLevel:10,spCost:'30'}}};
assert.equal(Codex.isValidCache(empty),true,'empty offline fallback is valid');
assert.equal(Codex.isValidCache({...empty,region:'kROM'}),false,'rejects non-classic server');
assert.equal(Codex.isValidCache({...empty,apiKey:'secret'}),false,'rejects embedded API key');
assert.equal(Codex.isValidCache({...sample,monsters:{'1002':{id:333,name:'wrong'}}}),false,'rejects mismatched record id');
assert.ok(Codex.render(sample,Core).includes('60'),'shows imported HP');
assert.ok(Codex.render(sample,Core).includes('50'),'shows original Pre-Renewal HP separately');
assert.ok(Codex.render(sample,Core).includes('ไม่ได้แทนที่'),'does not pretend API overwrote combat stats');
assert.ok(Codex.render(empty,Core).includes('ยังไม่ได้ Import'),'describes empty cache honestly');
const attack = {...empty,items:{'501':{id:501,name:'<img src=x onerror=alert(1)>'}}};
assert.ok(!Codex.render(attack,Core).includes('<img'),'encodes external names');
assert.ok(Codex.render(attack,Core).includes('&lt;img'),'retains safe text');
assert.equal(Codex.isValidCache({...empty,monsters:{'1002':{id:1002,name:'x',apiKey:'secret'}}}),false,'rejects secret fields in records');
console.log('CODEX PASS: 10 integration assertions');
